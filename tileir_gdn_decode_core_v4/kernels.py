import cuda.tile as ct
@ct.kernel
def core(X,A,B,AL,DT,S,O,I,Scale):
 n=ct.bid(0);hv=ct.bid(1);vb=ct.bid(2);hk=hv//2
 lane=ct.arange(32,dtype=ct.int32);vv=vb*32+ct.arange(32,dtype=ct.int32)
 slot=ct.gather(I,n)
 if slot<=0:
  ct.scatter(O,(n,0,hv,vv),ct.full((32,),0.0,ct.bfloat16))
 else:
  q0=ct.gather(X,(n,hk*128+lane*4+0)).astype(ct.float32);k0=ct.gather(X,(n,2048+hk*128+lane*4+0)).astype(ct.float32)
  q1=ct.gather(X,(n,hk*128+lane*4+1)).astype(ct.float32);k1=ct.gather(X,(n,2048+hk*128+lane*4+1)).astype(ct.float32)
  q2=ct.gather(X,(n,hk*128+lane*4+2)).astype(ct.float32);k2=ct.gather(X,(n,2048+hk*128+lane*4+2)).astype(ct.float32)
  q3=ct.gather(X,(n,hk*128+lane*4+3)).astype(ct.float32);k3=ct.gather(X,(n,2048+hk*128+lane*4+3)).astype(ct.float32)
  qs=q1*q1+q0*q0
  qs=qs+q2*q2
  qs=qs+q3*q3
  qs=ct.add(ct.extract(qs,(0,),(16,)),ct.extract(qs,(1,),(16,)),rounding_mode=ct.RoundingMode.RN)
  qs=ct.add(ct.extract(qs,(0,),(8,)),ct.extract(qs,(1,),(8,)),rounding_mode=ct.RoundingMode.RN)
  qs=ct.add(ct.extract(qs,(0,),(4,)),ct.extract(qs,(1,),(4,)),rounding_mode=ct.RoundingMode.RN)
  qs=ct.add(ct.extract(qs,(0,),(2,)),ct.extract(qs,(1,),(2,)),rounding_mode=ct.RoundingMode.RN)
  qs=ct.add(ct.extract(qs,(0,),(1,)),ct.extract(qs,(1,),(1,)),rounding_mode=ct.RoundingMode.RN)
  qr=ct.sqrt(ct.reshape(qs,())+1.e-6,rounding_mode=ct.RoundingMode.APPROX,flush_to_zero=True)
  q0=ct.truediv(q0,qr,rounding_mode=ct.RoundingMode.FULL)*Scale
  q1=ct.truediv(q1,qr,rounding_mode=ct.RoundingMode.FULL)*Scale
  q2=ct.truediv(q2,qr,rounding_mode=ct.RoundingMode.FULL)*Scale
  q3=ct.truediv(q3,qr,rounding_mode=ct.RoundingMode.FULL)*Scale
  ks=k1*k1+k0*k0
  ks=ks+k2*k2
  ks=ks+k3*k3
  ks=ct.add(ct.extract(ks,(0,),(16,)),ct.extract(ks,(1,),(16,)),rounding_mode=ct.RoundingMode.RN)
  ks=ct.add(ct.extract(ks,(0,),(8,)),ct.extract(ks,(1,),(8,)),rounding_mode=ct.RoundingMode.RN)
  ks=ct.add(ct.extract(ks,(0,),(4,)),ct.extract(ks,(1,),(4,)),rounding_mode=ct.RoundingMode.RN)
  ks=ct.add(ct.extract(ks,(0,),(2,)),ct.extract(ks,(1,),(2,)),rounding_mode=ct.RoundingMode.RN)
  ks=ct.add(ct.extract(ks,(0,),(1,)),ct.extract(ks,(1,),(1,)),rounding_mode=ct.RoundingMode.RN)
  kr=ct.sqrt(ct.reshape(ks,())+1.e-6,rounding_mode=ct.RoundingMode.APPROX,flush_to_zero=True)
  k0=ct.truediv(k0,kr,rounding_mode=ct.RoundingMode.FULL)
  k1=ct.truediv(k1,kr,rounding_mode=ct.RoundingMode.FULL)
  k2=ct.truediv(k2,kr,rounding_mode=ct.RoundingMode.FULL)
  k3=ct.truediv(k3,kr,rounding_mode=ct.RoundingMode.FULL)
  av=ct.gather(A,(n,hv)).astype(ct.float32);bv=ct.gather(B,(n,hv)).astype(ct.float32)
  al=ct.gather(AL,hv);dt=ct.gather(DT,hv).astype(ct.float32);gatex=av+dt
  sp=ct.where(gatex<=20.0,ct.log(1.0+ct.exp2(gatex*1.4426950408889634)),gatex)
  g=(0.0-ct.exp2(al*1.4426950408889634))*sp;decay=ct.exp2(g*1.4426950408889634)
  beta=ct.truediv(1.0,1.0+ct.exp2((0.0-bv)*1.4426950408889634),rounding_mode=ct.RoundingMode.FULL)
  v=ct.gather(X,(n,4096+hv*128+vv)).astype(ct.float32)
  h0=ct.gather(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+0,(1,32))))*decay
  h1=ct.gather(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+1,(1,32))))*decay
  h2=ct.gather(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+2,(1,32))))*decay
  h3=ct.gather(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+3,(1,32))))*decay
  dot=h0*ct.reshape(k0,(1,32))+h1*ct.reshape(k1,(1,32))
  dot=dot+h2*ct.reshape(k2,(1,32))
  dot=dot+h3*ct.reshape(k3,(1,32))
  dot=ct.add(ct.extract(dot,(0,0),(32,16)),ct.extract(dot,(0,1),(32,16)),rounding_mode=ct.RoundingMode.RN)
  dot=ct.add(ct.extract(dot,(0,0),(32,8)),ct.extract(dot,(0,1),(32,8)),rounding_mode=ct.RoundingMode.RN)
  dot=ct.add(ct.extract(dot,(0,0),(32,4)),ct.extract(dot,(0,1),(32,4)),rounding_mode=ct.RoundingMode.RN)
  dot=ct.add(ct.extract(dot,(0,0),(32,2)),ct.extract(dot,(0,1),(32,2)),rounding_mode=ct.RoundingMode.RN)
  dot=ct.add(ct.extract(dot,(0,0),(32,1)),ct.extract(dot,(0,1),(32,1)),rounding_mode=ct.RoundingMode.RN)
  delta=(v-ct.reshape(dot,(32,)))*beta
  h0=ct.reshape(k0,(1,32))*ct.reshape(delta,(32,1))+h0
  h1=ct.reshape(k1,(1,32))*ct.reshape(delta,(32,1))+h1
  h2=ct.reshape(k2,(1,32))*ct.reshape(delta,(32,1))+h2
  h3=ct.reshape(k3,(1,32))*ct.reshape(delta,(32,1))+h3
  total=h0*ct.reshape(q0,(1,32))+h1*ct.reshape(q1,(1,32))
  total=total+h2*ct.reshape(q2,(1,32))
  total=total+h3*ct.reshape(q3,(1,32))
  total=ct.add(ct.extract(total,(0,0),(32,16)),ct.extract(total,(0,1),(32,16)),rounding_mode=ct.RoundingMode.RN)
  total=ct.add(ct.extract(total,(0,0),(32,8)),ct.extract(total,(0,1),(32,8)),rounding_mode=ct.RoundingMode.RN)
  total=ct.add(ct.extract(total,(0,0),(32,4)),ct.extract(total,(0,1),(32,4)),rounding_mode=ct.RoundingMode.RN)
  total=ct.add(ct.extract(total,(0,0),(32,2)),ct.extract(total,(0,1),(32,2)),rounding_mode=ct.RoundingMode.RN)
  total=ct.add(ct.extract(total,(0,0),(32,1)),ct.extract(total,(0,1),(32,1)),rounding_mode=ct.RoundingMode.RN)
  ct.scatter(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+0,(1,32))),h0)
  ct.scatter(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+1,(1,32))),h1)
  ct.scatter(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+2,(1,32))),h2)
  ct.scatter(S,(slot,hv,ct.reshape(vv,(32,1)),ct.reshape(lane*4+3,(1,32))),h3)
  ct.scatter(O,(n,0,hv,vv),ct.reshape(total,(32,)).astype(ct.bfloat16))
